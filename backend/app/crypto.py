"""Fernet encryption for stored tokens. Key lives only in backend/.env (APP_SECRET)."""
import base64
import hashlib
import os
from pathlib import Path

from cryptography.fernet import Fernet
from dotenv import load_dotenv

ENV_PATH = Path(__file__).resolve().parent.parent / ".env"
load_dotenv(ENV_PATH)


def _key() -> bytes:
    key = os.getenv("APP_SECRET")
    if not key:
        key = Fernet.generate_key().decode()
        with ENV_PATH.open("a") as f:
            f.write(f"\nAPP_SECRET={key}\n")
        os.environ["APP_SECRET"] = key
    try:
        Fernet(key.encode())
        return key.encode()
    except ValueError:  # not a Fernet key, e.g. a value generated by the host: derive one from it
        return base64.urlsafe_b64encode(hashlib.sha256(key.encode()).digest())


def encrypt(plain: str) -> str:
    return Fernet(_key()).encrypt(plain.encode()).decode() if plain else ""


def decrypt(token: str) -> str:
    return Fernet(_key()).decrypt(token.encode()).decode() if token else ""
